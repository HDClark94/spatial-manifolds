from scipy.fft import fft, ifft, next_fast_len

from lfp_batch import FS, LFP_ROOT, clip_trials, nap, vr_paths

ROOT = '/Users/harryclark/Documents/spatial-manifolds'
OUT = f'{ROOT}/data/lfp/gamma_envelope_rate.csv'
OUT_PERI = f'{ROOT}/data/lfp/gamma_envelope_peri.npz'

BANDS = {'slow': (30., 48.), 'fast': (60., 100.)}
THETA = (6., 10.)
RUN_SPEED = 3.0
DEC = 5                    # ms per bin; 200 Hz, above both envelopes' bandwidth
MIN_SEP = 2                # groups between a cell and the envelope, ~120 um
MAX_SEP = 6                # and no further, ~360 um: gamma is local
MIN_INT = 3                # interneurons in the window, per envelope group
MIN_PRINC = 10
MAX_GROUPS = 6             # envelope groups per session, evenly spaced
N_SURR = 200
MAXLAG = 40                # bins, +/- 200 ms; a narrower window pins the peak
                           # at its own edge, which is the window choosing the
                           # answer rather than the data
PERI_HW = 40               # peri-event half-window, in bins (200 ms); at
                           # 60 ms both classes peaked on the edge
INT = 'putative interneuron'


def analytic(x, lo, hi):
    """Analytic signal in one band, from a single transform."""
    n = len(x)
    nf = next_fast_len(n)
    X = fft(x, nf)
    f = np.fft.fftfreq(nf, 1 / FS)
    Y = np.zeros(nf, complex)
    m = (f >= lo) & (f <= hi)
    Y[m] = 2.0 * X[m]
    return ifft(Y)[:n]


def block(v, k):
    """Mean over non-overlapping blocks of k samples."""
    n = (len(v) // k) * k
    return v[:n].reshape(-1, k).mean(1)


def phase_randomise(v, rng):
    """Same power spectrum, redrawn phases: the smoothness-matched surrogate."""
    n = len(v)
    V = np.fft.rfft(v - v.mean())
    ph = rng.uniform(-np.pi, np.pi, len(V))
    ph[0] = 0.0
    if n % 2 == 0:
        ph[-1] = 0.0
    return np.fft.irfft(np.abs(V) * np.exp(1j * ph), n) + v.mean()


def partial(y, x, Z):
    """Partial correlation of y and x given covariates Z (columns, no const)."""
    A = np.column_stack([np.ones(len(y)), Z])
    Q, _ = np.linalg.qr(A)
    yr = y - Q @ (Q.T @ y)
    xr = x - Q @ (Q.T @ x)
    sy, sx = yr.std(), xr.std()
    if sy == 0 or sx == 0:
        return np.nan, np.nan, Q, yr
    r = float(np.dot(yr, xr) / (len(y) * sy * sx))
    r2z = 1.0 - float(yr.var() / y.var()) if y.var() > 0 else np.nan
    return r, r2z, Q, yr


def partial_given(yr, x, Q):
    """Partial correlation reusing an existing basis and residualised y."""
    xr = x - Q @ (Q.T @ x)
    sy, sx = yr.std(), xr.std()
    if sy == 0 or sx == 0:
        return np.nan
    return float(np.dot(yr, xr) / (len(yr) * sy * sx))


def xcorr_lag(yr, xr, maxlag):
    """Lag (bins) of peak |cross-correlation|; positive = rate leads envelope."""
    n = len(yr)
    a = (yr - yr.mean()) / (yr.std() * np.sqrt(n))
    b = (xr - xr.mean()) / (xr.std() * np.sqrt(n))
    nf = next_fast_len(2 * n)
    c = np.fft.irfft(np.fft.rfft(a, nf) * np.conj(np.fft.rfft(b, nf)), nf)
    lags = np.arange(-maxlag, maxlag + 1)
    v = np.concatenate([c[-maxlag:], c[:maxlag + 1]])
    k = int(np.argmax(np.abs(v)))
    return int(lags[k]), float(v[k])


def run_session(mo, dy, ident, state, rng, peri):
    lf = f'{LFP_ROOT}/M{mo}/D{dy}/VR/sub-M{mo}_ses-D{dy}_typ-VR_beh.nwb'
    ana = f'{LFP_ROOT}/M{mo}/D{dy}/anatomy_M{mo}_D{dy}.csv'
    if not (os.path.exists(lf) and os.path.exists(ana)):
        # Say so rather than returning quietly. Under heavy I/O the LFP volume
        # drops out, os.path.exists goes False, and a silent [] is
        # indistinguishable from a session that genuinely has no data -- which
        # is how five M29 sessions vanished from a rerun without one error.
        print(f'  ? M{mo}D{dy}: LFP file not readable, SKIPPED', flush=True)
        return []
    fh = h5py.File(lf, 'r')
    if 'processing/ecephys/LFP/lfp/data' not in fh:
        fh.close(); return []
    names = [n.decode() for n in
             fh['general/extracellular_ephys/electrodes/channel_name'][:]]
    ch2g = {c: i for i, n in enumerate(names) for c in n.split('_')}
    A = pd.read_csv(ana)
    ent = {c for c, r in zip(A.channel_id, A.brain_region.astype(str))
           if r.startswith('ENTm')}
    eg = sorted({ch2g[c] for c in ent if c in ch2g})
    if len(eg) < 2 * MIN_SEP + 1:
        fh.close(); return []

    bp, cp = vr_paths(mo, dy)
    beh = nap.load_file(bp)
    clusters = nap.load_file(cp)
    trials, _ = clip_trials(beh['trials'].as_dataframe(), clusters)
    ec = clusters.metadata['extremum_channel']
    cells = []
    for c in [int(x) for x in clusters.index]:
        k = (mo, dy, c)
        if k not in ident:
            continue
        g = ch2g.get(str(ec[c]), -1)
        if g in eg:
            cells.append((c, g, ident[k] == INT))
    if sum(z for _, _, z in cells) < MIN_INT:
        fh.close(); return []

    # Envelope groups: evenly spaced through the entorhinal span, so the
    # own-group leak comparison and the beyond-the-leak result are measured on
    # the same fields rather than on different parts of the probe.
    want = sorted({eg[i] for i in
                   np.unique(np.linspace(0, len(eg) - 1, MAX_GROUPS).round()
                             .astype(int))})
    d = fh['processing/ecephys/LFP/lfp/data']
    nT = d.shape[0]
    blk = (d.chunks[0] if d.chunks else 26041) * 8
    X = np.empty((nT, len(want)), np.float32)
    for i in range(0, nT, blk):
        X[i:i + blk] = d[i:i + blk, :][:, want]
    fh.close()
    col = {g: i for i, g in enumerate(want)}

    t = np.arange(nT) / FS
    S = beh['S']
    spd = np.asarray(S.values)[np.searchsorted(np.asarray(S.index), t)
                               .clip(0, len(S) - 1)]
    run = spd >= RUN_SPEED

    # One mask per state, over running samples inside clipped trials.
    st_mask = {True: np.zeros(nT, bool), False: np.zeros(nT, bool)}
    inside = np.zeros(nT, bool)
    for _, tr in trials.iterrows():
        u = int(tr.number)
        m = (t >= tr.start) & (t <= tr.end)
        inside |= m
        if u in state:
            st_mask[bool(state[u])] |= m
    keep = run & inside

    nb = nT // DEC
    kb = block(keep.astype(float), DEC) > .999            # fully-running bins
    sb = block(spd, DEC)
    ab = {k: block(v.astype(float), DEC) > .5 for k, v in st_mask.items()}
    if kb.sum() < 2000:
        return []

    # Population rates, in spikes/s, per cell class and per distance window.
    sp_idx, is_int, grp = [], [], []
    for c, g, z in cells:
        ii = np.round(np.asarray(clusters[c].index, dtype=float) * FS)
        ii = ii[(ii >= 0) & (ii < nT)].astype(int) // DEC
        sp_idx.append(ii[ii < nb]); is_int.append(z); grp.append(g)
    is_int = np.array(is_int); grp = np.array(grp)

    def pop_rate(sel):
        if not sel.any():
            return None
        h = np.zeros(nb)
        for j in np.where(sel)[0]:
            h += np.bincount(sp_idx[j], minlength=nb)
        return h / (DEC / 1000.0) / sel.sum()

    rows = []
    for gl in want:
        sep = np.abs(grp - gl)
        win = (sep >= MIN_SEP) & (sep <= MAX_SEP)
        own = sep <= 1
        farw = sep > MAX_SEP
        n_i, n_p = int((win & is_int).sum()), int((win & ~is_int).sum())
        if n_i < MIN_INT or n_p < MIN_PRINC:
            continue
        R = {'int': pop_rate(win & is_int), 'princ': pop_rate(win & ~is_int),
             'int_own': pop_rate(own & is_int),
             'princ_own': pop_rate(own & ~is_int),
             'int_far': pop_rate(farw & is_int),
             'princ_far': pop_rate(farw & ~is_int)}
        th = block(np.abs(analytic(X[:, col[gl]].astype(float), *THETA)), DEC)
        for bn, (lo, hi) in BANDS.items():
            env = block(np.abs(analytic(X[:, col[gl]].astype(float), lo, hi)),
                        DEC)
            y = env[kb]
            Z = np.column_stack([R['princ'][kb], sb[kb], th[kb]])
            r_i, r2z, Q, yr = partial(y, R['int'][kb], Z)
            # and the principal rate's own partial, with the interneuron rate
            # moved into the covariates, so the two are symmetric
            r_p, _, Qp, yrp = partial(
                y, R['princ'][kb],
                np.column_stack([R['int'][kb], sb[kb], th[kb]]))
            row = dict(mouse=mo, day=dy, group=gl, band=bn, n_int=n_i,
                       n_princ=n_p, n_bins=int(kb.sum()), r_int=r_i,
                       r_princ=r_p, r2_cov=r2z,
                       dr2_int=(r_i * r_i) * (1 - r2z) if np.isfinite(r_i)
                       else np.nan)
            # the leak, drawn to scale: same cells' class, measured on the
            # group they were recorded on
            for tag, m_, other in (('own', own, 'princ_own'),
                                   ('far', farw, 'princ_far')):
                ni = int((m_ & is_int).sum())
                row[f'n_int_{tag}'] = ni
                if ni < 1 or R[f'int_{tag}'] is None:
                    row[f'r_int_{tag}'] = np.nan
                    continue
                cov = R[other][kb] if R[other] is not None else R['princ'][kb]
                row[f'r_int_{tag}'] = partial(
                    y, R[f'int_{tag}'][kb],
                    np.column_stack([cov, sb[kb], th[kb]]))[0]
            # surrogate null, for BOTH populations: the rate with its own
            # power spectrum kept and its phases redrawn, so the smoothness
            # that would otherwise manufacture a correlation is matched.
            for tag, cl, obs, basis, yres in (('int', 'int', r_i, Q, yr),
                                              ('princ', 'princ', r_p, Qp, yrp)):
                su = np.empty(N_SURR)
                for j_ in range(N_SURR):
                    su[j_] = partial_given(
                        yres, phase_randomise(R[cl], rng)[kb], basis)
                row[f'null_mean_{tag}'] = float(np.nanmean(su))
                row[f'null_sd_{tag}'] = float(np.nanstd(su))
                row[f'z_{tag}'] = ((obs - row[f'null_mean_{tag}'])
                                   / row[f'null_sd_{tag}']
                                   if row[f'null_sd_{tag}'] > 0 else np.nan)
                row[f'p_{tag}'] = float((np.abs(su) >= abs(obs)).mean())
            # direction, as a lag: positive means the rate leads the envelope
            xr_i = R['int'][kb] - Q @ (Q.T @ R['int'][kb])
            row['lag_int'], row['xc_int'] = xcorr_lag(yr, xr_i, MAXLAG)
            xr_p = R['princ'][kb] - Qp @ (Qp.T @ R['princ'][kb])
            row['lag_princ'], row['xc_princ'] = xcorr_lag(yrp, xr_p, MAXLAG)
            # by anchoring state, for the one claim the paper makes about state
            for tag, m in (('a', kb & ab[True]), ('n', kb & ab[False])):
                if m.sum() < 1000:
                    row[f'r_int_{tag}'] = row[f'r_princ_{tag}'] = np.nan
                    continue
                row[f'r_int_{tag}'] = partial(
                    env[m], R['int'][m],
                    np.column_stack([R['princ'][m], sb[m], th[m]]))[0]
                row[f'r_princ_{tag}'] = partial(
                    env[m], R['princ'][m],
                    np.column_stack([R['int'][m], sb[m], th[m]]))[0]
            rows.append(row)

            # peri-event rates: what each class does around an amplitude peak
            e = (env - env[kb].mean()) / env[kb].std()
            cand = np.where((e > 2) & kb)[0]
            pk = []
            for i in cand:
                if not pk or i - pk[-1] > PERI_HW:
                    pk.append(i)
            pk = [i for i in pk if PERI_HW <= i < nb - PERI_HW]
            if len(pk) >= 50:
                for cl in ('int', 'princ'):
                    v = R[cl]
                    z = (v - v[kb].mean()) / (v[kb].std() or 1)
                    seg = np.stack([z[i - PERI_HW:i + PERI_HW + 1] for i in pk])
                    peri.setdefault((bn, cl), []).append(seg.mean(0))
    return rows


if __name__ == '__main__':
    T = pd.read_csv(f'{ROOT}/data/population_state/anchoring_trials.csv')
    U = pd.read_csv(f'{ROOT}/data/population_state/unit_table.csv')
