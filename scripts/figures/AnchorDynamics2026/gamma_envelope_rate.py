"""Is either gamma band's AMPLITUDE built out of fast-spiking interneuron firing?

WHY THIS IS A DIFFERENT QUESTION FROM gamma_locking.py. That script asked
whether interneurons follow the gamma rhythm, and the answer was no in the
sense the model needs: interneurons are no more phase-locked than principal
cells in either band (p = 0.60 slow, 0.92 fast), and grid cells are the most
locked class of all. The one thing it did find is a PHASE result -- in 60-100 Hz
the interneurons fire a median 45 degrees later than the principal cells
(p = 9.6e-5), the direction PING predicts, with no such lag in 30-48 Hz.

But "the interneurons generate this rhythm" is a claim about AMPLITUDE, not
phase. A rhythm generated by a population should wax and wane with how hard
that population is firing. Locking cannot see that: a cell can be perfectly
locked to a rhythm it contributes nothing to. So this script asks the
generative question directly -- does the interneuron population's firing RATE
predict the band's envelope, over and above what the principal population's
rate predicts -- and asks it separately for the two bands, because the model
needs the answer to differ between them.

THREE TRAPS, ALL OF WHICH WOULD MANUFACTURE THE RESULT.

1. SPIKE LEAK, and it is worse here than for locking. A fast-spiking waveform
   leaks into the local field at exactly these frequencies, so interneuron rate
   against nearby gamma amplitude is partly a cell correlating with its own
   extracellular footprint -- and unlike a phase estimate, an amplitude
   estimate is contaminated in the direction of the hypothesis no matter what
   the timing is. Every reported number therefore builds the population rates
   from cells at least MIN_SEP channel groups (~120 um) from the group the
   envelope is measured on. The own-group value is computed too, purely to show
   the size of the artifact being avoided.

2. DISTANCE, in the other direction. Gamma is local, so pushing the cells far
   enough away manufactures a null as surely as the own channel manufactures a
   result. Cells are therefore taken from a window -- beyond MIN_SEP but within
   MAX_SEP (~360 um) -- nearest-beyond-the-leak, as in gamma_locking.py. The
   same quantity is computed for cells within one group (~60 um, inside the
   leak) and for cells beyond MAX_SEP, so the distance dependence can be read
   off three points rather than asserted: a leak falls away between the first
   and the second, a local field between the second and the third.

3. SMOOTHNESS. Both regressors and the envelope are smooth and strongly
   autocorrelated, so an ordinary p-value on half a million samples is
   meaningless: any smooth series predicts any other. The null here is
   PHASE-RANDOMISED interneuron rate -- the Fourier amplitudes kept, the phases
   redrawn -- which preserves the autocorrelation exactly and destroys only the
   timing relationship. The reported statistic is a z against that null.

WHAT IS CONTROLLED FOR. The principal population's rate is always in the model,
because the two rates covary and the question is specifically what the
interneurons add. Running speed and theta amplitude are in it too: both drive
firing rate and gamma amplitude, so either would otherwise arrive wearing an
interneuron label. Running samples only. The effect size reported is the
PARTIAL correlation of rate with envelope given those covariates, which is why
the covariates-only R2 is recorded alongside.

WHAT CANNOT BE CONCLUDED EITHER WAY. A positive partial correlation would not
show that interneurons generate the band; it shows that the band's amplitude
carries information about interneuron firing that principal firing does not,
which is the strongest statement this dataset supports. The rate-to-amplitude
cross-correlation lag is recorded so the direction can at least be inspected.

Writes data/lfp/gamma_envelope_rate.csv and data/lfp/gamma_envelope_peri.npz
"""
